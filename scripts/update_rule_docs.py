"""Regenerate the public Markdown rule catalog from the source catalog."""

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from siteaudit_kit.rules import RULES  # noqa: E402


def main():
    lines = ["# Rule catalog", "", "Generated by `scripts/update_rule_docs.py`.", "",
             "Static checks report evidence in supplied source. Advisory findings do not",
             "establish a browser failure, an SEO penalty, WCAG compliance, or security.", "",
             "| ID | Category | Severity | Finding |", "| --- | --- | --- | --- |"]
    for rule in RULES.values():
        lines.append(f"| {rule.id} | {rule.category} | {rule.severity} | {rule.title} |")
    for rule in RULES.values():
        lines.extend(["", f"## {rule.id} — {rule.title}", "", rule.fix, "",
                      f"[Primary reference]({rule.reference})"])
    (ROOT / "docs/RULES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
